const STRINGS = {
  en,
  fr,
  es,
  de,
  pt,
  it,
  "zh-CN": zhCN,
  ja,
};

// The selected locale is cached: t() is called hundreds of times per render
// and must not hit localStorage each time.
let currentLocale = null;

function readStoredLocale() {
  try {
    const stored = localStorage.getItem(LANG_STORAGE_KEY);
    if (stored && LOCALES.some((l) => l.code === stored)) {
      return stored;
    }
  } catch {
    // localStorage unavailable (e.g. no DOM in tests) — use the default.
  }
  return DEFAULT_LOCALE;
}

function getLocale() {
  if (currentLocale === null) currentLocale = readStoredLocale();
  return currentLocale;
}

function setLocale(code) {
  if (!LOCALES.some((l) => l.code === code)) return;
  currentLocale = code;
  try {
    localStorage.setItem(LANG_STORAGE_KEY, code);
  } catch {
    // Ignore persistence failures; the locale still applies for this session.
  }
  if (typeof document !== "undefined") {
    document.documentElement.lang = code;
    document.dispatchEvent(new CustomEvent("depradar:locale-changed"));
  }
}

// Sets <html lang> for the stored locale (setLocale only does so on change).
function initLocale() {
  if (typeof document !== "undefined") {
    document.documentElement.lang = getLocale();
  }
}

function t(key, vars) {
  const dict = STRINGS[getLocale()] || en;
  let str = dict[key] ?? en[key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      // A replacer function: a plain string would interpret "$&", "$1"... in
      // the value (a path or an error message can contain them).
      str = str.replaceAll(`{{${name}}}`, () => String(value ?? ""));
    }
  }
  return str;
}

function applyTranslations(root) {
  const scope = root || document;
  scope.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  scope.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
  scope.querySelectorAll("[data-i18n-title]").forEach((el) => {
    el.title = t(el.dataset.i18nTitle);
  });
  scope.querySelectorAll("[data-i18n-aria-label]").forEach((el) => {
    el.setAttribute("aria-label", t(el.dataset.i18nAriaLabel));
  });
}

const i18n = {
  LOCALES,
  DEFAULT_LOCALE,
  STRINGS,
  t,
  getLocale,
  setLocale,
  initLocale,
  applyTranslations,
};

if (typeof window !== "undefined") {
  window.i18n = i18n;
}

if (typeof module !== "undefined" && module.exports) {
  module.exports = i18n;
}
